const LANG_KEY = "portfolio.lang";

function detectLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "en" || saved === "fr") return saved;
  const nav = (navigator.language || "").toLowerCase();
  return nav.startsWith("fr") ? "fr" : "en";
}

function applyLang(lang) {
  const dict = translations[lang] || translations.en;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });

  localStorage.setItem(LANG_KEY, lang);
}

function initLang() {
  const lang = detectLang();
  applyLang(lang);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyLang(btn.getAttribute("data-lang"));
    });
  });
}

function initNav() {
  const toggle = document.getElementById("nav-toggle");
  const links = document.getElementById("nav-links");
  const header = document.getElementById("site-header");

  if (toggle && links) {
    toggle.addEventListener("click", () => {
      const open = links.classList.toggle("is-open");
      toggle.setAttribute("aria-expanded", open ? "true" : "false");
    });

    links.querySelectorAll("a").forEach((a) => {
      a.addEventListener("click", () => {
        links.classList.remove("is-open");
        toggle.setAttribute("aria-expanded", "false");
      });
    });
  }

  const onScroll = () => {
    if (!header) return;
    header.classList.toggle("is-scrolled", window.scrollY > 12);
  };
  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });
}

function initReveal() {
  const nodes = document.querySelectorAll(".reveal");
  if (!nodes.length) return;

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    nodes.forEach((n) => n.classList.add("is-visible"));
    return;
  }

  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          io.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );

  nodes.forEach((n) => io.observe(n));
}

function initContactForm() {
  const form = document.getElementById("contact-form");
  if (!form) return;

  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const submitButton = form.querySelector('button[type="submit"]');
    const lang = localStorage.getItem(LANG_KEY) || "en";
    const sending = lang === "fr" ? "Envoi..." : "Sending...";
    const okMsg =
      lang === "fr" ? "Message envoyé." : "Message sent successfully.";
    const failMsg =
      lang === "fr"
        ? "Échec de l'envoi. Réessayez ou écrivez à naderfkihhassen@gmail.com."
        : "Failed to send. Try again or email naderfkihhassen@gmail.com.";

    const original = submitButton.textContent;
    submitButton.textContent = sending;
    submitButton.disabled = true;

    fetch("https://formsubmit.co/ajax/naderfkihhassen@gmail.com", {
      method: "POST",
      body: new FormData(form),
      headers: { Accept: "application/json" },
    })
      .then((res) => {
        if (!res.ok) throw new Error("send failed");
        alert(okMsg);
        form.reset();
      })
      .catch(() => {
        alert(failMsg);
      })
      .finally(() => {
        submitButton.textContent = original;
        submitButton.disabled = false;
      });
  });
}

